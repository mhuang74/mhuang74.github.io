export const t = (locale: Locale, key: MessageKey): string =>
  messages[locale][key];

export const format = (
  template: string,
  values: Record<string, string | number>
): string =>
  template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in values ? String(values[name]) : match
  );
